using System.Globalization;

namespace SpireMind.Arena;

/// <summary>
/// Ironclad pool cards, part 1: the cards of cards-1.json (Aggression to Dominate) and the nine
/// powers only they use. Each follows its game class of the same name (v0.107.1); the order of
/// the steps inside every <c>Play</c> is the game's. Bash, Defend and Armaments of the same
/// spec file are in CoreCards. All card and power texts are our own wording.
/// </summary>
public sealed class Cards1 : IContentModule
{
    public void Register(Registry r)
    {
        r.Power<AggressionPower>();
        r.Power<BarricadePower>();
        r.Power<NoDrawPower>();
        r.Power<ColossusPower>();
        r.Power<CorruptionPower>();
        r.Power<CrimsonMantlePower>();
        r.Power<CrueltyPower>();
        r.Power<DarkEmbracePower>();
        r.Power<DemonFormPower>();

        // Demonic Shield gives Block to another player. The game takes multiplayer-only cards out
        // of every single-player pool, and with one player it can never be played.
        r.Exclude(ContentKind.Card, "DemonicShield", "multiplayer only: the game filters it out of every single-player card pool, and it needs another living player as its target");

        Attacks(r);
        Skills(r);
        Powers(r);
    }

    private static void Attacks(Registry r)
    {
        // Anger: 6 damage (8), then a copy of this card as it is now (upgrade, cost changes) goes
        // to the bottom of the discard pile; Anger itself follows it there.
        r.Card(new CardDef("Anger", "Anger", CardType.Attack, CardRarity.Common, 0, TargetType.AnyEnemy)
        {
            Vars = { ["Damage"] = 6 },
            Upgrade = c => c.Add("Damage", 2),
            Text = t => $"Deal {t.Damage()} damage. Add a copy of this card to your discard pile.",
            Play = c =>
            {
                c.Attack(c.V("Damage")).Execute();
                c.F.AddGeneratedCard(c.F.CloneCard(c.Card), PileType.Discard, PilePosition.Bottom, c.Owner);
            },
        });

        // Ashen Strike: 6 plus 3 (4) for every card in the exhaust pile, counted when the hit lands.
        // Strength is added once to the total. It is a Strike for effects that count Strikes.
        r.Card(new CardDef("AshenStrike", "Ashen Strike", CardType.Attack, CardRarity.Uncommon, 1, TargetType.AnyEnemy)
        {
            Tags = CardTags.Strike,
            Vars = { ["CalculationBase"] = 6, ["ExtraDamage"] = 3 },
            DamageMultiplier = (f, _, _) => f.ExhaustPile.Count,
            Upgrade = c => c.Add("ExtraDamage", 1),
            Text = t => $"Deal {t.CalculatedDamage()} damage ({t.N("CalculationBase")} plus {t.N("ExtraDamage")} for each card in your exhaust pile).",
            Play = c => c.CalculatedAttack().Execute(),
        });

        // Bludgeon: 32 damage (42).
        r.Card(new CardDef("Bludgeon", "Bludgeon", CardType.Attack, CardRarity.Uncommon, 3, TargetType.AnyEnemy)
        {
            Vars = { ["Damage"] = 32 },
            Upgrade = c => c.Add("Damage", 10),
            Text = t => $"Deal {t.Damage()} damage.",
            Play = c => c.Attack(c.V("Damage")).Execute(),
        });

        // Body Slam: damage equal to the player's Block when the hit lands; the Block is kept.
        // The upgrade makes it cost 0.
        r.Card(new CardDef("BodySlam", "Body Slam", CardType.Attack, CardRarity.Common, 1, TargetType.AnyEnemy)
        {
            Vars = { ["CalculationBase"] = 0, ["ExtraDamage"] = 1 },
            DamageMultiplier = (f, _, _) => f.Player.Block,
            Upgrade = c => c.UpgradeCostBy(-1),
            // Outside a fight there is no Block to read, so no number is shown.
            Text = t => t.F is null
                ? "Deal damage equal to your Block."
                : $"Deal damage equal to your Block ({t.CalculatedDamage()} right now).",
            Play = c => c.CalculatedAttack().Execute(),
        });

        // Break: 20 damage (30), then 5 Vulnerable (7). Ancient: never offered or generated by chance.
        r.Card(new CardDef("Break", "Break", CardType.Attack, CardRarity.Ancient, 1, TargetType.AnyEnemy)
        {
            Vars = { ["Damage"] = 20, ["Vulnerable"] = 5 },
            Upgrade = c =>
            {
                c.Add("Damage", 10);
                c.Add("Vulnerable", 2);
            },
            Text = t => $"Deal {t.Damage()} damage. Apply {t.N("Vulnerable")} Vulnerable.",
            Play = c =>
            {
                c.Attack(c.V("Damage")).Execute();
                c.Apply<VulnerablePower>(c.Target, c.V("Vulnerable"));
            },
        });

        // Breakthrough: lose 1 HP first, then 9 damage (13) to every enemy. If the HP loss kills
        // the player the attack does not happen.
        r.Card(new CardDef("Breakthrough", "Breakthrough", CardType.Attack, CardRarity.Common, 1, TargetType.AllEnemies)
        {
            Vars = { ["Damage"] = 9, ["HpLoss"] = 1 },
            Upgrade = c => c.Add("Damage", 4),
            Text = t => $"Lose {t.N("HpLoss")} HP. Deal {t.Damage()} damage to ALL enemies.",
            Play = c =>
            {
                c.LoseHp(c.V("HpLoss"));
                c.Attack(c.V("Damage")).Execute();
            },
        });

        // Bully: 4 plus 2 (3) for every stack of Vulnerable on the target. The Vulnerable factor
        // then applies on top. With no target (the hand text) only the 4 shows.
        r.Card(new CardDef("Bully", "Bully", CardType.Attack, CardRarity.Uncommon, 0, TargetType.AnyEnemy)
        {
            Vars = { ["CalculationBase"] = 4, ["ExtraDamage"] = 2 },
            DamageMultiplier = (_, _, target) => target?.PowerAmount<VulnerablePower>() ?? 0,
            Upgrade = c => c.Add("ExtraDamage", 1),
            Text = t => $"Deal {t.CalculatedDamage()} damage, plus {t.N("ExtraDamage")} for each Vulnerable on the enemy.",
            Play = c => c.CalculatedAttack().Execute(),
        });

        // Cinder: 18 damage (24), then one random card of the hand is exhausted (CombatCardSelection
        // stream, one draw; none with an empty hand). The game rolls even when the hit just won the fight.
        r.Card(new CardDef("Cinder", "Cinder", CardType.Attack, CardRarity.Common, 2, TargetType.AnyEnemy)
        {
            Vars = { ["Damage"] = 18 },
            Upgrade = c => c.Add("Damage", 6),
            Text = t => $"Deal {t.Damage()} damage. Exhaust a random card in your hand.",
            Play = c =>
            {
                c.Attack(c.V("Damage")).Execute();
                if (c.F.Rng.CombatCardSelection.NextItem(c.F.Hand) is { } card) c.F.Exhaust(card);
            },
        });

        // Conflagration: one attack of 4 hits (5), each for 2 on every enemy alive at that hit.
        r.Card(new CardDef("Conflagration", "Conflagration", CardType.Attack, CardRarity.Rare, 1, TargetType.AllEnemies)
        {
            Vars = { ["Damage"] = 2, ["Repeat"] = 4 },
            Upgrade = c => c.Add("Repeat", 1),
            Text = t => $"Deal {t.Damage()} damage to ALL enemies {t.N("Repeat")} times.",
            Play = c => c.Attack(c.V("Damage")).Hits((int)c.V("Repeat")).Execute(),
        });

        // Dismantle: 8 damage (10); two hits when the target has Vulnerable, looked at once before the attack.
        r.Card(new CardDef("Dismantle", "Dismantle", CardType.Attack, CardRarity.Uncommon, 1, TargetType.AnyEnemy)
        {
            Vars = { ["Damage"] = 8 },
            Upgrade = c => c.Add("Damage", 2),
            Text = t => $"Deal {t.Damage()} damage. If the enemy is Vulnerable, hit it twice.",
            Play = c =>
            {
                var hits = c.Target is { } target && target.HasPower<VulnerablePower>() ? 2 : 1;
                c.Attack(c.V("Damage")).Hits(hits).Execute();
            },
        });
    }

    private static void Skills(Registry r)
    {
        // Battle Trance: draw 3 (4), then No Draw: no other draw works for the rest of the turn.
        r.Card(new CardDef("BattleTrance", "Battle Trance", CardType.Skill, CardRarity.Uncommon, 0, TargetType.Self)
        {
            Vars = { ["Cards"] = 3 },
            Upgrade = c => c.Add("Cards", 1),
            Text = t => $"Draw {TextContext.Count(t.N("Cards"), "card")}. You cannot draw any more cards this turn.",
            Play = c =>
            {
                c.Draw(c.V("Cards"));
                c.ApplyToSelf<NoDrawPower>(1);
            },
        });

        // Blood Wall: lose 2 HP, then 16 Block (20).
        r.Card(new CardDef("BloodWall", "Blood Wall", CardType.Skill, CardRarity.Common, 2, TargetType.Self)
        {
            Vars = { ["HpLoss"] = 2, ["Block"] = 16 },
            Upgrade = c => c.Add("Block", 4),
            Text = t => $"Lose {t.N("HpLoss")} HP. Gain {t.Block()} Block.",
            Play = c =>
            {
                c.LoseHp(c.V("HpLoss"));
                c.GainBlock(c.V("Block"));
            },
        });

        // Bloodletting: lose 3 HP, then 2 energy (3). Energy is not capped at the maximum.
        r.Card(new CardDef("Bloodletting", "Bloodletting", CardType.Skill, CardRarity.Common, 0, TargetType.Self)
        {
            Vars = { ["HpLoss"] = 3, ["Energy"] = 2 },
            Upgrade = c => c.Add("Energy", 1),
            Text = t => $"Lose {t.N("HpLoss")} HP. Gain {t.N("Energy")} energy.",
            Play = c =>
            {
                c.LoseHp(c.V("HpLoss"));
                c.GainEnergy(c.V("Energy"));
            },
        });

        // Brand: lose 1 HP, exhaust a hand card the player picks (none: skipped; one: taken
        // without asking), then 1 Strength (2), also when nothing was exhausted.
        r.Card(new CardDef("Brand", "Brand", CardType.Skill, CardRarity.Rare, 0, TargetType.Self)
        {
            Vars = { ["HpLoss"] = 1, ["Strength"] = 1 },
            Upgrade = c => c.Add("Strength", 1),
            Text = t => $"Lose {t.N("HpLoss")} HP. Exhaust a card in your hand. Gain {t.N("Strength")} Strength.",
            Play = c =>
            {
                c.LoseHp(c.V("HpLoss"));
                if (c.F.ChooseHandCardToExhaust() is { } card) c.F.Exhaust(card);
                c.ApplyToSelf<StrengthPower>(c.V("Strength"));
            },
        });

        // Burning Pact: exhaust a hand card the player picks, then draw 2 (3) either way.
        r.Card(new CardDef("BurningPact", "Burning Pact", CardType.Skill, CardRarity.Uncommon, 1, TargetType.Self)
        {
            Vars = { ["Cards"] = 2 },
            Upgrade = c => c.Add("Cards", 1),
            Text = t => $"Exhaust a card in your hand. Draw {TextContext.Count(t.N("Cards"), "card")}.",
            Play = c =>
            {
                if (c.F.ChooseHandCardToExhaust() is { } card) c.F.Exhaust(card);
                c.Draw(c.V("Cards"));
            },
        });

        // Cascade: X cost. The top X cards (X+1 upgraded) leave the draw pile first and are then
        // played for free in that order, each going to its usual pile.
        r.Card(new CardDef("Cascade", "Cascade", CardType.Skill, CardRarity.Rare, CardDef.CostX, TargetType.Self)
        {
            Text = t => t.Upgraded
                ? "Play the top X+1 cards of your draw pile."
                : "Play the top X cards of your draw pile.",
            Play = c => c.F.AutoPlayFromDrawPile(c.X + (c.Upgraded ? 1 : 0), PilePosition.Top, forceExhaust: false),
        });

        // Colossus: 5 Block (8), then 1 turn of the Colossus power (the 1 does not change).
        r.Card(new CardDef("Colossus", "Colossus", CardType.Skill, CardRarity.Uncommon, 1, TargetType.Self)
        {
            Vars = { ["Block"] = 5, ["Colossus"] = 1 },
            Upgrade = c => c.Add("Block", 3),
            Text = t => $"Gain {t.Block()} Block. For {TextContext.Count(t.N("Colossus"), "turn")}, attacks by Vulnerable enemies deal half damage to you.",
            Play = c =>
            {
                c.GainBlock(c.V("Block"));
                c.ApplyToSelf<ColossusPower>(c.V("Colossus"));
            },
        });

        // Dominate: 1 Vulnerable (2) on the enemy, then Strength equal to all the Vulnerable it
        // has afterwards (none when Artifact stopped it and it had none). Exhaust, also upgraded.
        // StrengthPerVulnerable is only shown; the effect reads the Vulnerable amount itself.
        r.Card(new CardDef("Dominate", "Dominate", CardType.Skill, CardRarity.Uncommon, 1, TargetType.AnyEnemy)
        {
            Keywords = CardKeywords.Exhaust,
            Vars = { ["Vulnerable"] = 1, ["StrengthPerVulnerable"] = 1 },
            Upgrade = c => c.Add("Vulnerable", 1),
            Text = t => $"Apply {t.N("Vulnerable")} Vulnerable. Gain {t.N("StrengthPerVulnerable")} Strength for each Vulnerable on the enemy.",
            Play = c =>
            {
                c.Apply<VulnerablePower>(c.Target, c.V("Vulnerable"));
                c.ApplyToSelf<StrengthPower>(c.Target?.PowerAmount<VulnerablePower>() ?? 0);
            },
        });
    }

    private static void Powers(Registry r)
    {
        // Aggression: the upgrade only adds Innate.
        r.Card(new CardDef("Aggression", "Aggression", CardType.Power, CardRarity.Rare, 1, TargetType.Self)
        {
            Upgrade = c => c.Keywords |= CardKeywords.Innate,
            Text = _ => "At the start of your turn, a random Attack from your discard pile returns to your hand and is upgraded for the rest of combat.",
            Play = c => c.ApplyToSelf<AggressionPower>(1),
        });

        // Barricade: cost 3 (2).
        r.Card(new CardDef("Barricade", "Barricade", CardType.Power, CardRarity.Rare, 3, TargetType.Self)
        {
            Upgrade = c => c.UpgradeCostBy(-1),
            Text = _ => "Your Block is no longer removed at the start of your turn.",
            Play = c => c.ApplyToSelf<BarricadePower>(1),
        });

        // Corruption: cost 3 (2). Ancient: never offered or generated by chance.
        r.Card(new CardDef("Corruption", "Corruption", CardType.Power, CardRarity.Ancient, 3, TargetType.Self)
        {
            Vars = { ["Power"] = 1 },
            Upgrade = c => c.UpgradeCostBy(-1),
            Text = _ => "Skills cost 0. Whenever you play a Skill, Exhaust it.",
            Play = c => c.ApplyToSelf<CorruptionPower>(c.V("Power")),
        });

        // Crimson Mantle: 8 Block (10) at the start of every turn, and every play raises the HP
        // the power costs per turn by 1.
        r.Card(new CardDef("CrimsonMantle", "Crimson Mantle", CardType.Power, CardRarity.Rare, 1, TargetType.Self)
        {
            Vars = { ["CrimsonMantlePower"] = 8 },
            Upgrade = c => c.Add("CrimsonMantlePower", 2),
            Text = t => $"At the start of your turn, lose 1 HP and gain {t.N("CrimsonMantlePower")} Block.",
            Play = c => c.ApplyToSelf<CrimsonMantlePower>(c.V("CrimsonMantlePower"))?.IncrementSelfDamage(),
        });

        // Cruelty: 25 (50) hundredths on top of the 1.5 of Vulnerable for the player's attacks.
        r.Card(new CardDef("Cruelty", "Cruelty", CardType.Power, CardRarity.Rare, 1, TargetType.Self)
