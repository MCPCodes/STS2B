        });

        // Dark Embrace: cost 2 (1).
        r.Card(new CardDef("DarkEmbrace", "Dark Embrace", CardType.Power, CardRarity.Rare, 2, TargetType.Self)
        {
            Upgrade = c => c.UpgradeCostBy(-1),
