/// <summary>
/// Aggression: in the first step of its owner's turn (before Block falls, before energy and
/// before the hand draw) the Attacks of the discard pile are shuffled on the CombatCardSelection
/// stream and the first Amount of them move to the hand and are upgraded for the rest of the
/// fight. It is a pile move, not a draw. A card that finds the hand full lands back in the
/// discard pile and is upgraded all the same.
/// </summary>
public sealed class AggressionPower : Power
{
    public override string Name => "Aggression";
    public override PowerType Type => PowerType.Buff;

    public override string Describe() => Amount == 1
        ? "At the start of its turn, a random Attack from the discard pile returns to the hand and is upgraded."
        : string.Create(CultureInfo.InvariantCulture, $"At the start of its turn, {Amount} random Attacks from the discard pile return to the hand and are upgraded.");

    public override void BeforeSideTurnStart(Fight f, Side side, IReadOnlyList<Creature> participants)
    {
        if (!Owner.IsPlayer || !participants.Contains(Owner)) return;

        // The whole list is shuffled before the first Amount are taken: n Attacks cost n - 1 numbers.
        var attacks = f.DiscardPile.Where(c => c.Type == CardType.Attack).ToList();
        f.Rng.CombatCardSelection.Shuffle(attacks);
        foreach (var card in attacks.Take(Amount))
        {
            f.MoveCard(card, PileType.Hand);
            if (card.IsUpgradable) f.Upgrade(card);
        }
    }
}

/// <summary>Barricade: its owner's Block is not cleared at the start of its turn. Everyone else's still is.</summary>
public sealed class BarricadePower : Power
{
    public override string Name => "Barricade";
    public override PowerType Type => PowerType.Buff;
    public override PowerStackType StackType => PowerStackType.Single;

    public override string Describe() => "Block is not removed at the start of its turn.";

    public override bool ShouldClearBlock(Fight f, Creature creature) => !ReferenceEquals(Owner, creature);
}

/// <summary>
/// No Draw (Battle Trance): every draw of its owner draws nothing, except the hand draw at the
/// start of a turn. It goes at the end of its owner's turn, after the hand was discarded. A
/// debuff, so Artifact stops it.
/// </summary>
public sealed class NoDrawPower : Power
{
    public override string Name => "No Draw";
    public override PowerType Type => PowerType.Debuff;
    public override PowerStackType StackType => PowerStackType.Single;

    public override string Describe() => "Cannot draw cards for the rest of this turn.";

    // Every draw in the fight is the player's.
    public override bool ShouldDraw(Fight f, bool fromHandDraw) => fromHandDraw || !Owner.IsPlayer;

    public override void AfterSideTurnEnd(Fight f, Side side, IReadOnlyList<Creature> participants)
    {
        if (participants.Contains(Owner)) f.RemovePower(this);
    }
}

/// <summary>
/// Colossus: powered attacks that hit its owner from a dealer that has Vulnerable are halved.
/// The amount is a duration: it loses 1 at the end of every enemy turn, with a plain decrement
/// (no skipped first tick).
/// </summary>
public sealed class ColossusPower : Power
{
    public const decimal Factor = 0.5m;

    public override string Name => "Colossus";
    public override PowerType Type => PowerType.Buff;

    public override string Describe() => $"Takes half damage from attacks by Vulnerable enemies. Wears off in {Turns(Amount)}.";

    public override decimal ModifyDamageMultiplicative(Fight f, Creature? target, decimal amount, ValueProp props, Creature? dealer, CardInstance? cardSource) =>
        ReferenceEquals(target, Owner) && props.IsPoweredAttack() && dealer is not null && dealer.HasPower<VulnerablePower>() ? Factor : 1m;

    public override void AfterSideTurnEnd(Fight f, Side side, IReadOnlyList<Creature> participants)
    {
        if (side == Side.Enemy) f.Decrement(this);
    }
}

/// <summary>
/// Corruption: the player's Skills cost 0 (set in the late cost pass, so it beats cost changes
/// on the card; X costs are untouched) and a Skill that starts resolving is sent to the exhaust
/// pile, played by hand or by an effect. The destination is decided before a card's effect
/// runs, so a Skill already resolving when Corruption arrives is not exhausted by it.
/// </summary>
public sealed class CorruptionPower : Power
{
    public override string Name => "Corruption";
    public override PowerType Type => PowerType.Buff;
    public override PowerStackType StackType => PowerStackType.Single;

    public override string Describe() => "Skills cost 0 and are Exhausted when played.";

    // Every card in the fight is the player's, so "the card's owner has this power" is "the player has it".
    private bool Affects(CardInstance card) => Owner.IsPlayer && card.Type == CardType.Skill;

    public override decimal ModifyEnergyCostLate(Fight f, CardInstance card, decimal cost) => Affects(card) ? 0m : cost;

    public override (PileType Pile, PilePosition Position) ModifyCardPlayResultPile(Fight f, CardInstance card, bool isAutoPlay, PileType pile, PilePosition position) =>
        Affects(card) ? (PileType.Exhaust, position) : (pile, position);
}

/// <summary>
/// Crimson Mantle: right after its owner's hand draw it first costs its owner HP (ignores Block,
/// not modified, and without the "from a card or move" flag card HP loss carries), then gives
/// Amount Block that Dexterity and Frail do not change. The HP cost is a number of its own: it
/// starts at 0 and the card raises it by 1 with every play.
/// </summary>
public sealed class CrimsonMantlePower : Power
{
    /// <summary>HP lost at the start of each turn.</summary>
    public int SelfDamage { get; private set; }

    public override string Name => "Crimson Mantle";
    public override PowerType Type => PowerType.Buff;

    public override string Describe() =>
        string.Create(CultureInfo.InvariantCulture, $"At the start of its turn, loses {SelfDamage} HP and gains {Amount} Block.");

    /// <summary>What the card does after applying the power, on the new or the existing instance.</summary>
    public void IncrementSelfDamage() => SelfDamage++;

    public override void AfterPlayerTurnStart(Fight f)
    {
        if (!Owner.IsPlayer) return;
        f.Damage(Owner, SelfDamage, Props.NonCardHpLoss, Owner);
        f.GainBlock(Owner, Amount, Props.NonCardUnpowered);
    }
}

/// <summary>
/// Cruelty: a plain counter in hundredths. It has no hook of its own: Vulnerable asks the
/// dealer for it by name and adds Amount / 100 to its factor (1.5 becomes 1.75 at 25).
/// </summary>
public sealed class CrueltyPower : Power
{
    public override string Name => "Cruelty";
    public override PowerType Type => PowerType.Buff;

    public override string Describe() =>
        string.Create(CultureInfo.InvariantCulture, $"Its attacks deal {Amount}% more damage to Vulnerable enemies ({FactorText(Amount)} instead of x1.5).");

    /// <summary>"x1.75": the Vulnerable factor with this much Cruelty on the dealer.</summary>
    public static string FactorText(int amount) =>
        "x" + (VulnerablePower.Factor + amount / 100m).ToString("0.##", CultureInfo.InvariantCulture);
}

/// <summary>
/// Dark Embrace: whenever a card is exhausted, its owner draws Amount cards at once (an
/// ordinary draw: hand limit, No Draw). Exhausts by Ethereal at the end of the turn are only
/// counted; their cards are drawn in the last hook of the owner's turn, after the hand was
/// discarded, and so stay for the next turn.
/// </summary>
public sealed class DarkEmbracePower : Power
{
    private int _etherealExhausts;

    public override string Name => "Dark Embrace";
    public override PowerType Type => PowerType.Buff;

    public override string Describe() =>
        $"Whenever a card is Exhausted, draws {TextContext.Count(Amount, "card")}. For a card exhausted by Ethereal the draw comes after the hand is discarded.";

    public override void AfterCardExhausted(Fight f, CardInstance card, bool causedByEthereal)
    {
        if (!Owner.IsPlayer) return;
        if (causedByEthereal) _etherealExhausts++;
        else f.Draw(Amount);
    }

    public override void AfterSideTurnEnd(Fight f, Side side, IReadOnlyList<Creature> participants)
    {
        if (!participants.Contains(Owner)) return;
        // Asked even for 0 cards, and the count is forgotten even when No Draw blocked the draw.
        f.Draw(Amount * _etherealExhausts);
        _etherealExhausts = 0;
    }
}

/// <summary>Demon Form: at the start of each of its owner's turns, after the hand draw, its owner gains Amount Strength.</summary>
public sealed class DemonFormPower : Power
{
    public override string Name => "Demon Form";
    public override PowerType Type => PowerType.Buff;

    public override string Describe() =>
        string.Create(CultureInfo.InvariantCulture, $"At the start of its turn, gains {Amount} Strength.");

    public override void AfterSideTurnStart(Fight f, Side side, IReadOnlyList<Creature> participants)
    {
        if (participants.Contains(Owner)) f.ApplyPower<StrengthPower>(Owner, Amount, Owner);
    }
}
